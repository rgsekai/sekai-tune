package moe.rgsekai.sekaitune.lyrics.translation

import android.util.LruCache
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import moe.rgsekai.sekaitune.ai.AiLyricsDocumentParser
import moe.rgsekai.sekaitune.innertube.CaptionCue
import moe.rgsekai.sekaitune.innertube.VideoCaptions
import moe.rgsekai.sekaitune.innertube.YouTube
import moe.rgsekai.sekaitune.lyrics.CaptionAligner
import moe.rgsekai.sekaitune.lyrics.LyricsEntry
import moe.rgsekai.sekaitune.lyrics.LyricsUtils
import moe.rgsekai.sekaitune.lyrics.SongVideoMap
import moe.rgsekai.sekaitune.lyrics.VideoCaptionSource
import timber.log.Timber

/**
 * Loads uploaded (official studio, non-auto-generated) captions from YouTube and aligns them
 * with the song's lyrics.
 *
 * If >= 50% of the lines match the caption timing and cues, it uses the official studio translation.
 */
object YouTubeCaptionTranslation {

    private val availableCaptionsLanguagesCache = LruCache<String, Set<String>>(20)

    /**
     * Checks which languages the video has non-auto-generated uploaded captions for.
     */
    suspend fun getAvailableCaptionLanguages(videoId: String): Set<String> = withContext(Dispatchers.IO) {
        if (videoId.isBlank()) return@withContext emptySet()
        availableCaptionsLanguagesCache.get(videoId)?.let { return@withContext it }

        val captions = VideoCaptionSource.captions(videoId) ?: return@withContext emptySet()
        val uploadedLanguages = captions.tracks
            .filter { !it.isAutoGenerated }
            .mapNotNull { it.languageCode?.lowercase() }
            .toSet()

        availableCaptionsLanguagesCache.put(videoId, uploadedLanguages)
        uploadedLanguages
    }

    /**
     * Checks whether the video has uploaded captions matching [targetLanguageCode].
     */
    suspend fun hasCaptionInLanguage(videoId: String, targetLanguageCode: String): Boolean {
        val available = getAvailableCaptionLanguages(videoId)
        val target = GoogleTranslateEngine.normalizeLanguageCode(targetLanguageCode).lowercase()
        return available.any { VideoCaptionSource.sameLanguage(it, target) }
    }

    /**
     * Attempts to translate [rawLyrics] using the video's uploaded captions for [targetLanguageCode].
     * Returns null if:
     * - Video has no matching uploaded captions
     * - Alignment matching is < 50% of usable lines
     * - Alignment or cue assignment fails
     */
    suspend fun translateWithCaptions(
        videoId: String,
        rawLyrics: String,
        targetLanguageCode: String,
    ): String? = withContext(Dispatchers.IO) {
        if (videoId.isBlank() || rawLyrics.isBlank() || targetLanguageCode.isBlank()) return@withContext null

        val targetNormalized = GoogleTranslateEngine.normalizeLanguageCode(targetLanguageCode)
        val captions = VideoCaptionSource.captions(videoId) ?: return@withContext null

        val translationTrack = captions.tracks.firstOrNull {
            !it.isAutoGenerated && VideoCaptionSource.sameLanguage(it.languageCode, targetNormalized)
        } ?: return@withContext null

        val document = AiLyricsDocumentParser.parse(rawLyrics)
        val segments = document.segments
        if (segments.isEmpty()) return@withContext null

        val parsedEntries: List<LyricsEntry> = (if (LyricsUtils.isTtml(rawLyrics)) {
            runCatching { LyricsUtils.parseTtml(rawLyrics) }.getOrNull()
        } else if (LyricsUtils.isLineSyncedLrc(rawLyrics)) {
            runCatching { LyricsUtils.parseLyrics(rawLyrics) }.getOrNull()
        } else {
            null
        }) ?: return@withContext null

        val aligned = VideoCaptionSource.align(captions, parsedEntries, skipLanguage = targetNormalized) ?: return@withContext null

        val usable = aligned.alignment.usableLines
        val matched = aligned.alignment.matchedLines
        if (usable > 0 && (matched.toFloat() / usable.toFloat()) < 0.50f) {
            Timber.d("Caption alignment matched $matched / $usable (<50%), falling back to standard translation")
            return@withContext null
        }

        val translationCues = VideoCaptionSource.cues(captions, translationTrack) ?: return@withContext null
        val mappedLines: List<String?> = CaptionAligner.assignCues(parsedEntries, aligned.alignment.map, translationCues)

        val nonBlankCount = parsedEntries.count { it.text.isNotBlank() }
        val translatedCount = mappedLines.count { !it.isNullOrBlank() }
        if (nonBlankCount > 0 && (translatedCount * 2) < nonBlankCount) {
            Timber.d("Caption translation coverage too low ($translatedCount / $nonBlankCount), falling back")
            return@withContext null
        }

        val translatedMap = mutableMapOf<Int, String>()
        segments.forEachIndexed { index, segment ->
            val trans = mappedLines.getOrNull(index)?.takeIf { it.isNotBlank() }
            if (trans != null) {
                translatedMap[segment.id] = trans
            }
        }

        if (translatedMap.isEmpty()) return@withContext null
        document.rebuild(translatedMap)
    }
}

