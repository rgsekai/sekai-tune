package moe.rgsekai.sekaitune.lyrics

import android.os.SystemClock
import android.util.LruCache
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.withContext
import moe.rgsekai.sekaitune.innertube.CaptionCue
import moe.rgsekai.sekaitune.innertube.VideoCaptions
import moe.rgsekai.sekaitune.innertube.YouTube
import moe.rgsekai.sekaitune.innertube.models.response.PlayerResponse.Captions.CaptionTrack

internal object VideoCaptionSource {

    class Aligned(val track: CaptionTrack, val alignment: CaptionAligner.Alignment)

    private class Tracks(val captions: VideoCaptions?, val atMs: Long)

    private val tracks = LruCache<String, Tracks>(16)
    private val cues = LruCache<String, List<CaptionCue>>(16)
    private const val MissRetryMs = 30_000L
    private const val MaxUploadedTries = 3

    suspend fun captions(videoId: String): VideoCaptions? {
        tracks.get(videoId)?.let { cached ->
            if (cached.captions != null || SystemClock.elapsedRealtime() - cached.atMs < MissRetryMs) return cached.captions
        }
        val found = withContext(Dispatchers.IO) { YouTube.videoCaptions(videoId).getOrNull() }
        tracks.put(videoId, Tracks(found, SystemClock.elapsedRealtime()))
        return found
    }

    suspend fun cues(captions: VideoCaptions, track: CaptionTrack): List<CaptionCue>? {
        val key = "${captions.videoId}|${track.languageCode}|${track.kind}|${track.baseUrl.hashCode()}"
        cues.get(key)?.let { return it }
        val fetched = withContext(Dispatchers.IO) { YouTube.captionCues(captions, track).getOrNull() } ?: return null
        cues.put(key, fetched)
        return fetched
    }

    suspend fun align(captions: VideoCaptions, lines: List<LyricsEntry>, skipLanguage: String? = null): Aligned? {
        val auto = captions.tracks.firstOrNull { it.isAutoGenerated }
        val uploaded = captions.tracks
            .filter { !it.isAutoGenerated && (skipLanguage == null || !sameLanguage(it.languageCode, skipLanguage)) }
            .take(MaxUploadedTries)
        var best: Aligned? = null
        for (track in listOfNotNull(auto) + uploaded) {
            val trackCues = cues(captions, track) ?: continue
            val alignment = withContext(Dispatchers.Default) { CaptionAligner.align(lines, trackCues) } ?: continue
            if (track === auto) return Aligned(track, alignment)
            if (best == null || alignment.matchedLines > best.alignment.matchedLines) best = Aligned(track, alignment)
        }
        return best
    }

    fun sameLanguage(youtubeCode: String?, target: String): Boolean {
        val code = youtubeCode?.lowercase() ?: return false
        return when (val wanted = target.lowercase()) {
            "zh-cn" -> code in SimplifiedChinese
            "zh-tw" -> code in TraditionalChinese
            else -> baseLanguage(code) == baseLanguage(wanted)
        }
    }

    private fun baseLanguage(code: String): String = code.substringBefore('-').let { LanguageAliases[it] ?: it }

    private val SimplifiedChinese = setOf("zh-hans", "zh-cn", "zh-sg", "zh-my")
    private val TraditionalChinese = setOf("zh-hant", "zh-tw", "zh-hk", "zh-mo")

    private val LanguageAliases = mapOf(
        "iw" to "he",
        "in" to "id",
        "ji" to "yi",
        "jw" to "jv",
    )
}

